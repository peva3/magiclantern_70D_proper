/* Palette 6 ("Custom Range") is defined in terms of IRE percentages (0..100),
 * but every caller passes raw 8-bit luma (0..255) - the Y byte of YUV422 in
 * LiveView, and (i<<8)/HIST_WIDTH from the histogram.  Convert once here so
 * that the menu numbers mean what they say instead of being ~2.55x too low. */
static int ire_to_luma(int ire)
{
    if (ire < 0) ire = 0;
    if (ire > 100) ire = 100;
    return ire * 255 / 100;
}

int falsecolor_value_ex(int palette, int i)
{
    if (i < 0) i = 0;
    if (i > 255) i = 255;

    if (palette == 6) {
        int lo = ire_to_luma(falsecolor_custom_min);
        int hi = ire_to_luma(falsecolor_custom_max);
        if (i < lo) return 0x09;
        if (i > hi) return 0x08;
        int range = hi - lo;
        if (range <= 0) range = 1;
        int pct = (i - lo) * 100 / range;
        if (pct < 25) return 0x06;
        if (pct < 50) return 0x31;
        if (pct < 75) return 0x0F;
        return 0x13;
    }

    /* false_colour[] has only 6 rows.  falsecolor_palette is a CONFIG_INT read
     * verbatim from ML/SETTINGS, so a stale or hand-edited CFG can hold 7+ (or
     * a negative value) and index past the end of the table. */
    if (palette < 0 || palette >= (int)COUNT(false_colour)) palette = 0;
    return false_colour[palette][i];
}

int falsecolor_value(int i)
{
  return falsecolor_value_ex(falsecolor_palette, i);
}

int falsecolor_fordraw(int i)
{
  return falsecolor_draw ? falsecolor_value_ex(falsecolor_palette, i) : COLOR_WHITE;
}

